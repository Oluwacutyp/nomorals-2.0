"""Golden harness for edit_engine renders (Echelon Wave 1.2e).

Fixed synthetic sources → fixed specs → frame-sampled comparisons.
Whole-file bytes are NOT the golden (encoder variance); sampled
frame statistics are: mean RGB over the full frame, a center crop,
and a bottom strip (where captions/lower-thirds live). ffmpeg is
the fixture generator and the frame oracle; PIL does the stats.

Goldens live in ``tests/golden/edit_engine_goldens.json`` and are
recorded from real renders (see the record functions in
``tests/test_edit_engine_golden.py``). A golden diff makes a render
regression *visual*: the failing stat names the region and the
channel that moved.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from nomorals.media_edit.videos import run_ffmpeg

GOLDENS_PATH = Path(__file__).parent / "golden" / "edit_engine_goldens.json"


def color_source(path: Path, color: str, *, w: int = 320, h: int = 180,
                 seconds: float = 1.0, fps: int = 30) -> str:
    """A solid-color video fixture, generated by ffmpeg/lavfi."""
    run_ffmpeg(["-f", "lavfi", "-i",
                f"color=c={color}:s={w}x{h}:r={fps}:d={seconds}",
                "-c:v", "libx264", "-pix_fmt", "yuv420p", str(path)])
    return str(path)


def pattern_source(path: Path, *, w: int = 320, h: int = 180,
                   seconds: float = 2.0, fps: int = 30,
                   pattern: str = "testsrc2") -> str:
    """A moving-pattern video fixture (testsrc2 by default)."""
    run_ffmpeg(["-f", "lavfi", "-i",
                f"{pattern}=s={w}x{h}:r={fps}:d={seconds}",
                "-c:v", "libx264", "-pix_fmt", "yuv420p", str(path)])
    return str(path)


def _mean_rgb(img: Any) -> list[float]:
    px = img.convert("RGB")
    n = px.width * px.height
    sr = sg = sb = 0
    for r, g, b in px.getdata():
        sr += r
        sg += g
        sb += b
    return [round(sr / n, 2), round(sg / n, 2), round(sb / n, 2)]


def frame_stats(video: str | Path, t: float, *,
                workdir: Path) -> dict[str, list[float]]:
    """Sample one frame → {mean, center, bottom} mean-RGB stats."""
    from PIL import Image

    png = Path(workdir) / f"frame_{t:.3f}.png"
    run_ffmpeg(["-ss", f"{t:.3f}", "-i", str(video), "-frames:v", "1",
                "-y", str(png)])
    img = Image.open(png)
    w, h = img.size
    center = img.crop((w // 4, h // 4, 3 * w // 4, 3 * h // 4))
    bottom = img.crop((0, 3 * h // 4, w, h))
    return {"mean": _mean_rgb(img), "center": _mean_rgb(center),
            "bottom": _mean_rgb(bottom)}


def load_goldens() -> dict[str, Any]:
    return json.loads(GOLDENS_PATH.read_text(encoding="utf-8"))


def diff_stats(actual: dict[str, list[float]],
               expected: dict[str, list[float]],
               tol: float = 6.0) -> list[str]:
    """Human-readable diffs between two stat sets ([] = match)."""
    diffs: list[str] = []
    for region, exp_vals in expected.items():
        act_vals = actual.get(region)
        if act_vals is None:
            diffs.append(f"{region}: missing (expected {exp_vals})")
            continue
        for ch, (a, e) in enumerate(zip(act_vals, exp_vals)):
            if abs(a - e) > tol:
                diffs.append(
                    f"{region}[{'RGB'[ch]}]: got {a}, golden {e} "
                    f"(tol {tol})")
    return diffs
