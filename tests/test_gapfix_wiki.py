# ── board export ─────────────────────────────────────────────────────


class TestBoardExport(unittest.TestCase):
    def test_sections_become_nodes_chained_by_arrows(self) -> None:
        from nomorals.wiki.board import export_to_board

        with tempfile.TemporaryDirectory(prefix="nm-test-wiki-") as tmp:
            store = _store(tmp)
            store.create("Devon", "Intro.\n\n## What it is\nA.\n\n## What it does\nB.\n",
                         type="overview")
            doc = export_to_board(store, "devon")
            texts = [s for s in doc.shapes if s.type == "text"]
            self.assertEqual(len(texts), 3)
            self.assertIn("Devon", texts[0].props["text"])
            arrows = [s for s in doc.shapes if s.type == "arrow"]
            self.assertEqual(len(arrows), 2)

    def test_board_export_persists(self) -> None:
        from nomorals.media.edit_engine.board import BoardStore
        from nomorals.wiki.board import export_to_board

        with tempfile.TemporaryDirectory(prefix="nm-test-wiki-") as tmp:
            store = _store(tmp)
            store.create("Devon", "Intro.\n\n## What it is\nA.\n",
                         type="overview")
            doc = export_to_board(store, "devon")
            boards = BoardStore(dir=Path(tmp) / "boards")
            boards.save(doc)
            loaded = boards.load(doc.id)
            assert loaded is not None
            self.assertEqual(loaded.title, "Wiki: Devon")

    def test_board_export_missing_page_raises(self) -> None:
        from nomorals.wiki.board import export_to_board

        with tempfile.TemporaryDirectory(prefix="nm-test-wiki-") as tmp:
            store = _store(tmp)
            with self.assertRaises(ValueError):
                export_to_board(store, "nope")


# ── tool + verb + registry ───────────────────────────────────────────


class TestToolVerb(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory(prefix="nm-test-wiki-")
        self.store = _store(self._tmp.name)
        _seed(self.store)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def _registry(self):
        from nomorals.tools import registry as tool_registry
        from nomorals.tools import wiki as wiki_tool

        reg = tool_registry.ToolRegistry(SimpleNamespace(
            settings=SimpleNamespace(home_path=Path(self._tmp.name)),
            db=None, router=None))
        wiki_tool.register(reg)
        return reg

    def _call(self, reg, **kw):
        return reg._tools["wiki"].fn(**kw)

    def test_tool_registers(self) -> None:
        reg = self._registry()
        self.assertIsNotNone(reg.get("wiki"))

    def test_tool_create_read_search(self) -> None:
        reg = self._registry()
        created = self._call(reg, action="create", title="New Page",
                             body="Hello wiki.\n", type="guide")
        self.assertTrue(created["ok"])
        self.assertEqual(created["slug"], "new-page")
        read = self._call(reg, action="read", slug="new-page")
        self.assertTrue(read["ok"])
        self.assertEqual(read["page"]["title"], "New Page")
        found = self._call(reg, action="search", query="hello")
        self.assertTrue(found["ok"])
        self.assertEqual([p["slug"] for p in found["results"]],
                         ["new-page"])

    def test_tool_broken_names_the_link(self) -> None:
        reg = self._registry()
        out = self._call(reg, action="broken")
        self.assertTrue(out["ok"])
        self.assertEqual(len(out["broken"]), 1)
        self.assertEqual(out["broken"][0]["target"], "Missing Page")

    def test_tool_unknown_action_is_honest(self) -> None:
        reg = self._registry()
        out = self._call(reg, action="explode")
        self.assertFalse(out["ok"])
        self.assertIn("unknown action", out["error"])

    def test_tool_import_markdown(self) -> None:
        reg = self._registry()
        text = "---\ntitle: Imported\ntype: guide\n---\nBody.\n"
        out = self._call(reg, action="import", text=text)
        self.assertTrue(out["ok"])
        self.assertEqual(out["slug"], "imported")

    def test_verb_board_list_read(self) -> None:
        from nomorals.agents.partner.runtime_system import (
            RuntimeSystemMixin,
        )

        runtime = object.__new__(RuntimeSystemMixin)
        runtime._wiki_store = lambda: self.store
        board = runtime._control_wiki("", chat_key="telegram:1")
        self.assertIn("Devon", board)
        self.assertIn("GoldenSwing", board)
        listed = runtime._control_wiki("list", chat_key="telegram:1")
        self.assertIn("/wiki read devon", listed)
        read = runtime._control_wiki("read devon", chat_key="telegram:1")
        self.assertIn("Devon is the personal AI", read)
        missing = runtime._control_wiki("read nope", chat_key="telegram:1")
        self.assertIn("no page", missing)

    def test_verb_broken_and_orphans(self) -> None:
        from nomorals.agents.partner.runtime_system import (
            RuntimeSystemMixin,
        )

        runtime = object.__new__(RuntimeSystemMixin)
        runtime._wiki_store = lambda: self.store
        out = runtime._control_wiki("broken", chat_key="telegram:1")
        self.assertIn("Missing Page", out)
        self.assertIn("goldenswing", out)
        orphans = runtime._control_wiki("orphans", chat_key="telegram:1")
        self.assertIn("orphan-note", orphans)


class TestWiring(unittest.TestCase):
    def test_control_commands_cover_wiki(self) -> None:
        from nomorals.social.chat.control import (
            _HELP_GROUPS,
            CONTROL_COMMANDS,
            LIST_GROUPS,
            list_catalog,
        )

        self.assertIn("wiki", CONTROL_COMMANDS)
        grouped = [k for _, kinds in LIST_GROUPS for k in kinds]
        self.assertEqual(grouped.count("wiki"), 1)
        helped = [k for _, kinds in _HELP_GROUPS for k in kinds]
        self.assertEqual(helped.count("wiki"), 1)
        self.assertIn("/wiki", list_catalog())

    def test_public_commands_unmoved(self) -> None:
        from nomorals.social.chat.control import PUBLIC_COMMANDS

        self.assertEqual(len(PUBLIC_COMMANDS), 279)

    def test_nl_question_matches_known_pages_only(self) -> None:
        from nomorals.tools.wiki import parse_wiki_question

        with tempfile.TemporaryDirectory(prefix="nm-test-wiki-") as tmp:
            store = _store(tmp)
            _seed(store)
            known = [(p.slug, p.title) for p in store.list_pages()]
            hit = parse_wiki_question("what does the wiki say about Devon?",
                                      known)
            self.assertEqual(hit, ("read", "devon"))
            hit = parse_wiki_question("search the wiki for gold", known)
            self.assertEqual(hit, ("search", "gold"))
            self.assertIsNone(parse_wiki_question(
                "what does the wiki say about Zanzibar?", known))
            self.assertIsNone(parse_wiki_question(
                "what is the weather today?", known))


