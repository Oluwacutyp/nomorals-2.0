def _store(tmp: str) -> WikiStore:
    return WikiStore(wiki_path(SimpleNamespace(home_path=Path(tmp))))


def _seed(store: WikiStore) -> None:
    store.create("Devon", "Devon is the personal AI.\n\nSee [[GoldenSwing]] for trading.\n",
                 type="overview", category="Core",
                 summary="The personal AI herself.")
    store.create("GoldenSwing", "GoldenSwing trades gold.\n\nSee [[Devon]] and [[Missing Page]].\n",
                 type="guide", category="Trading")
    store.create("Orphan Note", "Nobody links here.\n", type="reference")


# ── slugs + frontmatter ──────────────────────────────────────────────


class TestSlugs(unittest.TestCase):
    def test_slugify(self) -> None:
        self.assertEqual(slugify("GoldenSwing Trading Desk"), "goldenswing-trading-desk")
        self.assertEqual(slugify("  What Is Devon?  "), "what-is-devon")
        self.assertEqual(slugify("C++ & Rust!"), "c-rust")
        self.assertEqual(slugify("a--b"), "a-b")

    def test_slugify_rejects_empty(self) -> None:
        with self.assertRaises(ValueError):
            slugify("!!!")

    def test_frontmatter_round_trip(self) -> None:
        page = Page(slug="devon", title="Devon", body="Hello.\n",
                    type="overview", category="Core",
                    summary="The personal AI.", tags=["ai", "core"],
                    order=0, parent="")
        text = emit_frontmatter(page) + page.body
        parsed, body = parse_frontmatter(text)
        self.assertEqual(parsed["title"], "Devon")
        self.assertEqual(parsed["type"], "overview")
        self.assertEqual(parsed["category"], "Core")
        self.assertEqual(parsed["summary"], "The personal AI.")
        self.assertEqual(parsed["tags"], ["ai", "core"])
        self.assertEqual(parsed["order"], 0)
        self.assertEqual(body, "Hello.\n")

    def test_frontmatter_missing_is_empty(self) -> None:
        parsed, body = parse_frontmatter("No header here.\n")
        self.assertEqual(parsed, {})
        self.assertEqual(body, "No header here.\n")

    def test_frontmatter_rejects_bad_type(self) -> None:
        with self.assertRaises(ValueError):
            parse_frontmatter("---\ntitle: X\ntype: nope\n---\nBody.\n")


# ── store ────────────────────────────────────────────────────────────


class TestStore(unittest.TestCase):
    def setUp(self) -> None:
        self._tmp = tempfile.TemporaryDirectory(prefix="nm-test-wiki-")
        self.store = _store(self._tmp.name)

    def tearDown(self) -> None:
        self._tmp.cleanup()

    def test_create_get_list(self) -> None:
        page = self.store.create("Devon", "Body.\n", type="overview")
        self.assertEqual(page.slug, "devon")
        self.assertEqual(page.title, "Devon")
        got = self.store.get("devon")
        assert got is not None
        self.assertEqual(got.body, "Body.\n")
        self.assertEqual([p.slug for p in self.store.list_pages()], ["devon"])

    def test_duplicate_title_gets_unique_slug(self) -> None:
        self.store.create("Devon", "One.\n")
        second = self.store.create("Devon", "Two.\n")
        self.assertEqual(second.slug, "devon-2")

    def test_create_rejects_empty_title_and_body(self) -> None:
        with self.assertRaises(ValueError):
            self.store.create("", "Body.\n")
        with self.assertRaises(ValueError):
            self.store.create("Title", "")

    def test_create_rejects_bad_type(self) -> None:
        with self.assertRaises(ValueError):
            self.store.create("Title", "Body.\n", type="nope")

    def test_update_keeps_revision_history(self) -> None:
        self.store.create("Devon", "First.\n")
        self.store.update("devon", "Second.\n", note="rewrite")
        page = self.store.get("devon")
        assert page is not None
        self.assertEqual(page.body, "Second.\n")
        self.assertEqual(len(page.revisions), 1)
        self.assertEqual(page.revisions[0]["body"], "First.\n")
        self.assertEqual(page.revisions[0]["note"], "rewrite")

    def test_revert_restores_old_body(self) -> None:
        self.store.create("Devon", "First.\n")
        self.store.update("devon", "Second.\n")
        self.store.update("devon", "Third.\n")
        self.assertTrue(self.store.revert("devon", 1))
        page = self.store.get("devon")
        assert page is not None
        self.assertEqual(page.body, "First.\n")

    def test_revert_bad_revision_is_false(self) -> None:
        self.store.create("Devon", "First.\n")
        self.assertFalse(self.store.revert("devon", 9))

    def test_delete_and_missing(self) -> None:
        self.store.create("Devon", "Body.\n")
        self.assertTrue(self.store.delete("devon"))
        self.assertIsNone(self.store.get("devon"))
        self.assertFalse(self.store.delete("devon"))
        self.assertFalse(self.store.update("devon", "x\n"))

    def test_persists_across_instances(self) -> None:
        self.store.create("Devon", "Body.\n", type="overview")
        again = _store(self._tmp.name)
        got = again.get("devon")
        assert got is not None
        self.assertEqual(got.title, "Devon")
        self.assertEqual(got.type, "overview")

    def test_sorted_pages_troubleshooting_last(self) -> None:
        self.store.create("Zebra Fix", "Fix.\n", type="troubleshooting")
        self.store.create("Apple Guide", "Guide.\n", type="guide", order=2)
        self.store.create("Banana Guide", "Guide.\n", type="guide", order=1)
        slugs = [p.slug for p in self.store.list_pages()]
        self.assertEqual(slugs, ["banana-guide", "apple-guide", "zebra-fix"])

    def test_import_markdown_reads_frontmatter(self) -> None:
        text = ("---\ntitle: Imported\ntype: guide\ncategory: Test\n"
                "tags: a, b\n---\nImported body.\n")
        page = self.store.import_markdown(text)
        self.assertEqual(page.slug, "imported")
        self.assertEqual(page.type, "guide")
        self.assertEqual(page.tags, ["a", "b"])
        self.assertEqual(page.body, "Imported body.\n")


