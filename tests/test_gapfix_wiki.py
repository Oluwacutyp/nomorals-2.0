"""Devon's wiki — a durable knowledge surface, mined from the
storytold craft-wiki patterns (docs/pattern only: craft-wiki carries
NO licence, so this is original Devon code implementing the mined
patterns, never a copy of its text or files).

craft-wiki is an Astro + Starlight docs site: 258 markdown docs under
``src/content/docs/apps/<app>/``, per-app pages (overview order 0,
getting-started 1, install-update, workflows 3, troubleshooting last),
frontmatter (title, description, sidebar.order, plus parent / type /
category / subcategory / summary / cover), an autogenerated sidebar
(order, then label, troubleshooting last), absolute links between
pages, and an editor behind Discord auth. What Devon takes from it:
the page model (slug + frontmatter + type + category + parent),
the per-topic templates, the sidebar ordering rule, and the
link/backlink discipline — superseded into a LIVE organ: pages are
created, edited, searched, linked and revised from chat and from the
brain, with full revision history, a broken-link report that names
the link, and exports onto the board.

Failing-first: on the pristine base every import below raises
``ModuleNotFoundError`` (no ``nomorals/wiki``) and the wiring tests
fail for the missing verb/tool/registry entries.
"""

