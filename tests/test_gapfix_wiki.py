    def test_backlinks(self) -> None:
        self.assertEqual(backlinks_for(self.store, "devon"), ["goldenswing"])
        self.assertEqual(backlinks_for(self.store, "goldenswing"), ["devon"])

    def test_orphans(self) -> None:
        self.assertEqual([p.slug for p in orphan_pages(self.store)],
                         ["orphan-note"])

    def test_broken_links_name_the_link(self) -> None:
        broken = broken_links(self.store)
        self.assertEqual(len(broken), 1)
        self.assertEqual(broken[0]["from"], "goldenswing")
        self.assertEqual(broken[0]["target"], "Missing Page")


