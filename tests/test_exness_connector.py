class MoneyGateTest(unittest.TestCase):
    def _trading_routes(self, http: FakeHttp) -> None:
        http.route("GET", "/v1/trading/access-point",
                   FakeResponse(200, {"access_point": "https://t.exness.com",
                                      "account_id": "1042"}))
        http.route("POST", "/v1/trading/accounts/1042/positions",
                   FakeResponse(200, {"status": "accepted",
                                      "operation_id": "op-1"}))
        http.route("GET",
                   "/v1/configuration/accounts/1042/instruments/EURUSD/conditions",
                   FakeResponse(200, {"instrument": "EURUSD",
                                      "point_digits": 5}))

    def test_open_position_needs_confirmation(self):
        conn, _http = _connected()
        with self.assertRaises(ConnectorError) as ctx:
            conn.open_position("EURUSD", "buy", 0.01)
        self.assertIn("confirmation", str(ctx.exception))

    def test_open_position_confirmed(self):
        conn, http = _connected()
        self._trading_routes(http)
        out = conn.open_position("EURUSD", "buy", 0.01, stop_loss=1.05,
                                 take_profit=1.20, confirmed=True)
        self.assertEqual(out["operation_id"], "op-1")
        method, url, data, headers = http.calls[-1]
        self.assertEqual(method, "POST")
        self.assertIn("/positions", url)
        body = json.loads(data.decode())
        self.assertEqual(body["instrument"], "EURUSD")
        self.assertEqual(body["side"], "buy")
        # prices rounded to the instrument's 5 point digits
        self.assertEqual(body["stop_loss_price"], "1.05000")
        self.assertEqual(body["take_profit_price"], "1.20000")
        self.assertIn("EXN-SIGN", headers)
        self.assertTrue(headers["EXN-IDEMPOTENCY-KEY"])

    def test_close_position_needs_confirmation(self):
        conn, _http = _connected()
        with self.assertRaises(ConnectorError):
            conn.close_position("pos-9")

    def test_pending_order_validation(self):
        conn, http = _connected()
        with self.assertRaises(ExnessError):
            conn.place_pending_order("limit", "EURUSD", "buy", 0.01,
                                     confirmed=True)  # no price

    def test_resume_checkpoint_rejects_unknown_stage(self):
        conn, _http = _connected()
        cp = mock.Mock()
        cp.resume_state = {"stage": "nope", "op": "nope"}
        with self.assertRaises(ExnessError):
            conn.resume_checkpoint(cp, db=object())


