"""Play & Downloads Phase 2 — the procedural animated cover
(doc 8, demonstrator 1 second half).

The render path is REAL on any host with ffmpeg + Pillow: a sine
tone generated by ffmpeg itself is analyzed (its measured RMS
envelope), drawn by Pillow, encoded by ffmpeg with the track's own
audio, and the result must probe as a decodable video.  Hosts
without the toolchain skip the render tests — the failure-honesty
tests still run, because "cannot render" must be a report, never
a fake artifact.
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path
from unittest import mock

import pytest

from tests.test_play_progress_demonstrator import _chat, _collect, _handler

_HAVE_FFMPEG = bool(shutil.which("ffmpeg"))
try:
    import PIL  # noqa: F401

    _HAVE_PIL = True
except ImportError:
    _HAVE_PIL = False

needs_render = pytest.mark.skipif(
    not (_HAVE_FFMPEG and _HAVE_PIL),
    reason="cover render needs ffmpeg + Pillow on this host")


def _tone(tmp_path: Path, seconds: int = 3) -> Path:
    out = tmp_path / "tone.mp3"
    subprocess.run(
        ["ffmpeg", "-y", "-v", "error", "-f", "lavfi",
         "-i", f"sine=frequency=440:duration={seconds}",
         "-metadata", "title=Tone", "-metadata", "artist=Test",
         str(out)],
        check=True, capture_output=True, timeout=60)
    return out


@needs_render
def test_envelope_is_measured_from_the_audio(tmp_path):
    from nomorals.media.cover_video import audio_envelope

    tone = _tone(tmp_path, seconds=2)
    env = audio_envelope(str(tone), seconds=2.0, fps=10)
    assert env is not None
    assert len(env) == 20
    assert max(env) > 0.9          # a full-scale sine peaks the scale
    assert min(env) > 0.3          # ...and never drops to silence


@needs_render
def test_render_produces_a_real_decodable_video(tmp_path):
    from nomorals.media.cover_video import render_cover_video
    from nomorals.media.library import read_metadata

    tone = _tone(tmp_path, seconds=3)
    out = tmp_path / "cover.mp4"
    report = render_cover_video(
        str(tone), str(out), title="Tone", artist="Test",
        seconds=2.0, size=256, fps=8)
    assert report.ok, report.error
    assert report.envelope == "measured"
    assert report.artwork in ("embedded", "procedural")
    assert report.frames == 16
    assert out.stat().st_size > 0
    duration = float(read_metadata(str(out)).get("duration") or 0)
    assert duration > 0.5


def test_render_of_a_non_audio_file_fails_honestly(tmp_path):
    from nomorals.media.cover_video import render_cover_video

    bogus = tmp_path / "song.mp3"
    bogus.write_bytes(b"<html><body>not audio</body></html>" * 16)
    out = tmp_path / "cover.mp4"
    report = render_cover_video(str(bogus), str(out), title="X")
    assert not report.ok
    assert report.error
    assert not out.is_file() or out.stat().st_size == 0


def test_render_without_ffmpeg_is_a_report_not_a_crash(tmp_path,
                                                        monkeypatch):
    import nomorals.media.cover_video as cover

    monkeypatch.setattr(cover, "_ffmpeg", lambda: "")
    report = cover.render_cover_video(
        str(tmp_path / "x.mp3"), str(tmp_path / "o.mp4"))
    assert not report.ok and "ffmpeg" in report.error


# ── handler wiring: after the track, gated, never instead of it ─────

@needs_render
def test_cover_video_follows_a_delivery_when_enabled(tmp_path):
    from nomorals.media.download_kit import ResumeDownloader
    from nomorals.media.playback import PlaybackEngine

    tone = _tone(tmp_path, seconds=3)
    body = tone.read_bytes()
    rt = _handler(tmp_path)
    rt.context.settings.media_cover_video = True
    chat = _chat()

    def head(url):
        return {"content_length": len(body), "etag": "v1",
                "last_modified": ""}

    def stream(url, start, end):
        data = body[start:]
        for i in range(0, len(data), 4096):
            yield data[i:i + 4096]

    item = {"kind": "url", "path": "https://good.test/tone.mp3",
            "title": "Tone", "artist": "Test", "downloadable": True}
    engine = PlaybackEngine(rt.context)
    with mock.patch("nomorals.tools.media.download",
                    side_effect=RuntimeError("yt-dlp seam down")), \
            mock.patch.multiple(
                ResumeDownloader,
                _default_head=staticmethod(head),
                _default_get_range_stream=staticmethod(stream)):
        rt._play_download_bg(
            chat, chat.key, "⏳ Tone",
            lambda: rt._play_send_with_fallthrough(
                engine, item, [], [], chat, query="Tone"),
            title="Tone")
        job = _collect(chat.key, title="Tone")
    assert job.result["sent"] is True
    # The track first, then exactly one video — the cover.
    assert len(rt.gateway.files) == 2
    audio_path, cover_path = rt.gateway.files[0][2], rt.gateway.files[1][2]
    assert audio_path.endswith(".mp3")
    assert cover_path.endswith(".mp4")
    from nomorals.media.library import read_metadata

    assert float(read_metadata(cover_path).get("duration") or 0) > 0


