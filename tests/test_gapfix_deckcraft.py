def _read(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


class ModelTests(unittest.TestCase):
    def test_simple_inspect(self) -> None:
        doc = DeckDocument.from_bytes(_read("simple.pptx"))
        self.assertEqual(len(doc.slides), 2)
        self.assertEqual(doc.slide_size, (12192000, 6858000))
        self.assertEqual(doc.core_properties.get("title"),
                         "Simple Fixture")
        slide1, slide2 = doc.slides
        self.assertEqual(slide1.text.count("Simple Fixture"), 1)
        self.assertIn("A deck made by Devon's own writer", slide1.text)
        self.assertEqual(slide1.transition, "fade")
        self.assertEqual(slide1.notes, "Speaker notes for slide one.")
        self.assertEqual(len(slide2.shapes), 4)
        kinds = [s.kind for s in slide2.shapes]
        self.assertEqual(kinds, ["shape", "shape", "shape", "table"])
        table = slide2.shapes[3]
        self.assertEqual(table.table,
                         [["Name", "Value"], ["Alpha", "1"], ["Beta", "2"]])
        accent = slide2.shapes[2]
        self.assertEqual(accent.fill, "4472C4")
        self.assertEqual(accent.geometry, "rect")

    def test_styled_inspect(self) -> None:
        doc = DeckDocument.from_bytes(_read("styled.pptx"))
        self.assertEqual(len(doc.images), 1)
        self.assertEqual(doc.slides[0].transition, "fade")
        runs = doc.slides[0].shapes[1].paragraphs[0].runs
        self.assertEqual([r.text for r in runs],
                         ["Bold Red", " and ", "Italic", " and ", "Plain"])
        self.assertTrue(runs[0].bold)
        self.assertEqual(runs[0].color, "FF0000")
        self.assertEqual(runs[0].size_half_points, 64)  # 32pt
        self.assertTrue(runs[2].italic)
        pic = doc.slides[0].shapes[2]
        self.assertEqual(pic.kind, "picture")
        self.assertEqual(pic.image_part, "ppt/media/image1.png")

    def test_charts_inspect(self) -> None:
        doc = DeckDocument.from_bytes(_read("charts.pptx"))
        slide = doc.slides[0]
        kinds = [s.kind for s in slide.shapes]
        self.assertIn("chart", kinds)
        self.assertIn("table", kinds)
        chart = next(s for s in slide.shapes if s.kind == "chart")
        self.assertEqual(chart.chart_title, "Sales")
        placeholder = next(
            s for s in slide.shapes if s.placeholder_type == "chart")
        self.assertEqual(placeholder.kind, "shape")

    def test_empty_inspect(self) -> None:
        doc = DeckDocument.from_bytes(_read("empty.pptx"))
        self.assertEqual(len(doc.slides), 1)
        self.assertEqual(doc.slides[0].shapes, [])
        self.assertEqual(doc.slides[0].text, "")

    def test_layouts_and_masters_inventoried(self) -> None:
        doc = DeckDocument.from_bytes(_read("simple.pptx"))
        self.assertEqual(len(doc.masters), 1)
        self.assertGreaterEqual(len(doc.layouts), 2)
        self.assertEqual(doc.layouts[0].kind, "title")

    def test_no_edit_round_trip_is_byte_identical(self) -> None:
        original = _read("simple.pptx")
        doc = DeckDocument.from_bytes(original)
        self.assertEqual(doc.to_bytes(), original)

    def test_broken_and_notpres_refused(self) -> None:
        from nomorals.documents.errors import DocumentError
        for name in ("broken.pptx", "notpres.pptx"):
            with self.assertRaises(DocumentError) as ctx:
                DeckDocument.from_bytes(_read(name))
            self.assertEqual(ctx.exception.kind, "parse")

    def test_fidelity_report_clean_on_unedited(self) -> None:
        original = _read("simple.pptx")
        doc = DeckDocument.from_bytes(original)
        report = doc.fidelity_report(original)
        self.assertEqual(report["untouched_slides_changed"], 0)
        self.assertEqual(report["parts_changed"], [])


class EditorTests(unittest.TestCase):
    def test_replace_text(self) -> None:
        editor = DeckEditor.from_bytes(_read("simple.pptx"))
        replaced = editor.replace_text("First point", "Opening point")
        self.assertEqual(replaced, 1)
        saved = editor.save()
        doc = DeckDocument.from_bytes(saved)
        self.assertIn("Opening point", doc.plain_text())
        self.assertNotIn("First point", doc.plain_text())
        report = editor.document.fidelity_report(_read("simple.pptx"))
        self.assertEqual(report["untouched_slides_changed"], 0)
        self.assertEqual(set(report["parts_changed"]),
                         {"ppt/slides/slide2.xml"})

    def test_restyle_run(self) -> None:
        editor = DeckEditor.from_bytes(_read("styled.pptx"))
        editor.set_run_format(0, 1, 0, 0, bold=False, italic=True,
                              color="00FF00", size_half_points=48)
        doc = DeckDocument.from_bytes(editor.save())
        run = doc.slides[0].shapes[1].paragraphs[0].runs[0]
        self.assertFalse(run.bold)
        self.assertTrue(run.italic)
        self.assertEqual(run.color, "00FF00")
        self.assertEqual(run.size_half_points, 48)

    def test_add_slide_and_text_box(self) -> None:
        editor = DeckEditor.from_bytes(_read("simple.pptx"))
        index = editor.add_slide(layout="content", title="New Slide")
        self.assertEqual(index, 2)
        editor.add_text_box(index, "Hello from the editor")
        doc = DeckDocument.from_bytes(editor.save())
        self.assertEqual(len(doc.slides), 3)
        self.assertIn("New Slide", doc.slides[2].text)
        self.assertIn("Hello from the editor", doc.slides[2].text)

    def test_add_table(self) -> None:
        editor = DeckEditor.from_bytes(_read("simple.pptx"))
        editor.add_table(0, ["A", "B"], [["1", "2"], ["3", "4"]])
        doc = DeckDocument.from_bytes(editor.save())
        tables = [s for s in doc.slides[0].shapes if s.kind == "table"]
        self.assertEqual(len(tables), 1)
        self.assertEqual(tables[0].table,
                         [["A", "B"], ["1", "2"], ["3", "4"]])

    def test_add_image(self) -> None:
        editor = DeckEditor.from_bytes(_read("simple.pptx"))
        img = Image.new("RGB", (40, 30), (10, 200, 90))
        buf = io.BytesIO()
        img.save(buf, format="PNG")
        editor.add_image(0, buf.getvalue())
        doc = DeckDocument.from_bytes(editor.save())
        self.assertEqual(len(doc.images), 1)
        pics = [s for s in doc.slides[0].shapes if s.kind == "picture"]
        self.assertEqual(len(pics), 1)
        self.assertEqual(pics[0].image_part, "ppt/media/image1.png")

    def test_remove_and_reorder_slides(self) -> None:
        editor = DeckEditor.from_bytes(_read("simple.pptx"))
        editor.remove_slide(0)
        doc = DeckDocument.from_bytes(editor.save())
        self.assertEqual(len(doc.slides), 1)
        self.assertIn("Content", doc.slides[0].text)
        editor2 = DeckEditor.from_bytes(_read("simple.pptx"))
        editor2.move_slide(0, 1)
        doc2 = DeckDocument.from_bytes(editor2.save())
        self.assertEqual(len(doc2.slides), 2)
        self.assertIn("Content", doc2.slides[0].text)
        self.assertIn("Simple Fixture", doc2.slides[1].text)

    def test_notes_and_metadata(self) -> None:
        editor = DeckEditor.from_bytes(_read("simple.pptx"))
        editor.set_notes(1, "Notes for the content slide.")
        editor.set_metadata(title="Retitled", author="Devon")
        doc = DeckDocument.from_bytes(editor.save())
        self.assertEqual(doc.slides[1].notes,
                         "Notes for the content slide.")
        self.assertEqual(doc.core_properties.get("title"), "Retitled")
        self.assertEqual(doc.core_properties.get("author"), "Devon")

    def test_transition(self) -> None:
        editor = DeckEditor.from_bytes(_read("empty.pptx"))
        editor.set_transition(0, "wipe")
        doc = DeckDocument.from_bytes(editor.save())
        self.assertEqual(doc.slides[0].transition, "wipe")

    def test_add_slide_title_on_blank_layout(self) -> None:
        # A blank layout has no title placeholder: the title must
        # arrive as a real title text box, never silently dropped.
        editor = DeckEditor.create(title="Blank Deck")
        index = editor.add_slide(layout="content", title="Second Slide")
        doc = DeckDocument.from_bytes(editor.save())
        self.assertIn("Second Slide", doc.slides[index].text)
        title_shapes = [s for s in doc.slides[index].shapes
                        if s.placeholder_type == "title"]
        self.assertEqual(len(title_shapes), 1)

    def test_create_blank(self) -> None:
        editor = DeckEditor.create(title="Blank Deck", author="Devon")
        saved = editor.save()
        doc = DeckDocument.from_bytes(saved)
        self.assertEqual(len(doc.slides), 1)
        self.assertEqual(doc.core_properties.get("title"), "Blank Deck")
        self.assertEqual(doc.slides[0].shapes, [])


class RenderTests(unittest.TestCase):
    def test_render_slide_png(self) -> None:
        doc = DeckDocument.from_bytes(_read("simple.pptx"))
        png = render_slide_to_png(doc, 1, width=960)
        img = Image.open(io.BytesIO(png))
        self.assertEqual(img.size, (960, 540))
        self.assertEqual(img.getpixel((10, 10)), (255, 255, 255))
        # accent box: fill 4472C4 at 7.5in/6in, 2.5in x 1in — check a
        # pixel below the box's text line, inside the fill
        self.assertEqual(img.getpixel((700, 490))[:3], (68, 114, 196))

    def test_render_reports_unrendered(self) -> None:
        doc = DeckDocument.from_bytes(_read("charts.pptx"))
        png = render_slide_to_png(doc, 0, width=960)
        img = Image.open(io.BytesIO(png))
        self.assertEqual(img.size, (960, 540))


