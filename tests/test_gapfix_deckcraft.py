class ToolTests(unittest.TestCase):
    def _registry(self) -> ToolRegistry:
        registry = ToolRegistry(context=SimpleNamespace(
            settings=SimpleNamespace(), home=Path(tempfile.mkdtemp())))
        registry.register_builtins()
        return registry

    def _call(self, registry: ToolRegistry, **kwargs) -> dict:
        outcome = registry.call("deckcraft", **kwargs)
        if hasattr(outcome, "value"):
            return outcome.value
        return outcome

    def test_tool_is_registered(self) -> None:
        registry = self._registry()
        spec = registry.get("deckcraft")
        self.assertIsNotNone(spec)
        self.assertIn("inspect", spec.description)

    def test_tool_inspect(self) -> None:
        registry = self._registry()
        out = self._call(registry, action="inspect",
                         sources=[str(FIXTURES / "simple.pptx")])
        self.assertEqual(len(out["slides"]), 2)
        self.assertEqual(out["core_properties"]["title"],
                         "Simple Fixture")
        self.assertIn("reply", out)

    def test_tool_edit_round_trip(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / "in.pptx"
            src.write_bytes(_read("simple.pptx"))
            out_path = Path(tmp) / "out.pptx"
            registry = self._registry()
            out = self._call(
                registry, action="replace", sources=[str(src)],
                output=str(out_path),
                text="First point", new_text="Replaced through the tool.")
            self.assertTrue(out["ok"])
            self.assertEqual(out["replacements"], 1)
            doc = DeckDocument.from_bytes(out_path.read_bytes())
            self.assertIn("Replaced through the tool.", doc.plain_text())

    def test_tool_render(self) -> None:
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / "in.pptx"
            src.write_bytes(_read("simple.pptx"))
            out_path = Path(tmp) / "slide.png"
            registry = self._registry()
            out = self._call(
                registry, action="render", sources=[str(src)],
                output=str(out_path), slide=1)
            self.assertTrue(out["ok"])
            img = Image.open(out_path)
            self.assertEqual(img.size, (960, 540))

    def test_tool_parity_and_attribution(self) -> None:
        registry = self._registry()
        out = self._call(registry, action="parity")
        self.assertEqual(out["failed"], 0)
        out = self._call(registry, action="attribution")
        self.assertEqual(out["failed"], 0)


