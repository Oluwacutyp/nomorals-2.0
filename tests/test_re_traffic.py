"""RE Pass 3 — the traffic rung as Evidence.

The capture fixtures were generated byte-honestly during the
build: a Python writer built the pcap packet-by-packet with
correct checksums (DNS for example.test, a cleartext HTTP
exchange, a TLS 1.2 session whose Certificate message carries a
real openssl-generated self-signed cert for secret.example.test,
ARP + ICMP), and the same packets were re-wrapped as pcapng;
every protocol count asserted here was corroborated by the real
TShark 4.2.2 hierarchy over the same file, whose verbatim output
is itself a fixture. The .mitm fixture and the addon JSONL are
from a real mitmdump run of Devon's own addon against a local
origin. Nothing here touches a live interface.
"""

from __future__ import annotations

import hashlib
import json
import tempfile
import unittest
from pathlib import Path
from types import SimpleNamespace

from nomorals.agents.reverse import ReEngine, traffic
from nomorals.agents.reverse.evidence import EvidenceStore
from nomorals.agents.reverse.mitm_scripts import devon_capture_addon as addon
from nomorals.storage.db import Database

FIXTURES = Path(__file__).parent / "fixtures"


def _fx(name: str) -> bytes:
    return (FIXTURES / name).read_bytes()


def _dissect(name: str, kind: str) -> dict:
    data = _fx(name)
    packets, _fmt = traffic.read_packets(data, kind)
    return traffic.dissect(packets, kind)


class _TmpHome:
    def __enter__(self):
        self.dir = tempfile.mkdtemp(prefix="re-tr-")
        return self.dir

    def __exit__(self, *exc):
        return False


class SniffTest(unittest.TestCase):
    def test_sniffs_every_capture_kind_by_content(self):
        self.assertEqual(traffic.sniff(_fx("re_capture.pcap")),
                         "pcap")
        self.assertEqual(traffic.sniff(_fx("re_capture.pcapng")),
                         "pcapng")
        self.assertEqual(traffic.sniff(_fx("re_capture.har")), "har")
        self.assertEqual(traffic.sniff(_fx("re_capture.mitm")),
                         "mitm-flows")
        self.assertTrue(traffic.sniff_addon(
            _fx("re_mitm_addon.jsonl")))

    def test_negatives(self):
        self.assertIsNone(traffic.sniff(b"\x7fELF" + bytes(200)))
        self.assertIsNone(
            traffic.sniff(_fx("re_firmware_image.bin")))
        self.assertIsNone(traffic.sniff(b""))
        self.assertFalse(traffic.sniff_addon(b'{"unrelated": 1}\n'))


class DissectTest(unittest.TestCase):
    def test_protocol_census_matches_recorded_tshark(self):
        facts = _dissect("re_capture.pcap", "pcap")
        self.assertEqual(facts["packets"], 17)
        recorded = traffic.parse_tshark_stats(
            _fx("re_tshark_fixture.txt").decode())
        for proto, row in facts["protocols"].items():
            self.assertEqual(row["frames"],
                             recorded["protocols"][proto]["frames"],
                             proto)
            self.assertEqual(row["bytes"],
                             recorded["protocols"][proto]["bytes"],
                             proto)

    def test_dns_query_and_answer(self):
        facts = _dissect("re_capture.pcap", "pcap")
        queries = facts["dns"]["queries"]
        self.assertEqual(len(queries), 1)
        self.assertEqual(queries[0]["questions"][0]["name"],
                         "example.test")
        responses = facts["dns"]["responses"]
        self.assertEqual(len(responses), 1)
        answers = responses[0]["answers"]
        self.assertEqual(answers[0]["value"], "93.184.216.34")

    def test_tls_facts_from_the_handshake(self):
        facts = _dissect("re_capture.pcap", "pcap")
        self.assertEqual(len(facts["tls"]["sessions"]), 1)
        sess = facts["tls"]["sessions"][0]
        self.assertEqual(sess["sni"], "secret.example.test")
        self.assertIn("TLS 1.3", sess["client_versions"])
        self.assertEqual(sess["version"], "TLS 1.2")
        self.assertEqual(sess["cipher"],
                         "ECDHE-RSA-AES128-GCM-SHA256")
        self.assertEqual(sess["certificates"][0]["subject"]["CN"],
                         "secret.example.test")
        self.assertEqual(sess["certificates"][0]["issuer"]["O"],
                         "Devon Fixture")
        # encrypted application data is counted, never decoded
        self.assertEqual(sess["opaque_bytes"], 32)

    def test_http_exchange_and_conversations(self):
        facts = _dissect("re_capture.pcap", "pcap")
        self.assertEqual(len(facts["http"]["exchanges"]), 1)
        ex = facts["http"]["exchanges"][0]
        self.assertEqual(ex["method"], "GET")
        self.assertEqual(ex["host"], "example.test")
        self.assertEqual(ex["status"], 200)
        endpoints = {(c["a"], c["b"]) for c in facts["conversations"]}
        self.assertTrue(any("93.184.216.34" in b
                            for _a, b in endpoints))

    def test_pcapng_parity_with_pcap(self):
        a = _dissect("re_capture.pcap", "pcap")
        b = _dissect("re_capture.pcapng", "pcapng")
        for key in ("packets", "protocols", "conversations", "dns",
                    "tls", "http"):
            self.assertEqual(a[key], b[key], key)


class TsharkParseTest(unittest.TestCase):
    def test_stats_parser_on_recorded_output(self):
        stats = traffic.parse_tshark_stats(
            _fx("re_tshark_fixture.txt").decode())
        self.assertEqual(stats["protocols"]["tls"]["frames"], 3)
        convs = {(c["a"], c["b"]) for c in stats["conversations"]}
        self.assertTrue(any("192.0.2.53:53" in b
                            for _a, b in convs))

    def test_fields_parser_on_recorded_output(self):
        text = _fx("re_tshark_fixture.txt").decode()
        fields_text = text.split("=== fields ===")[1]
        fields = traffic.parse_tshark_fields(fields_text)
        self.assertEqual(fields["dns_names"],
                         ["example.test", "example.test"])
        self.assertEqual(fields["dns_answers"], ["93.184.216.34"])
        self.assertEqual(fields["sni"], ["secret.example.test"])
        self.assertEqual(fields["http"][0],
                         {"method": "GET", "uri": "/index.html",
                          "host": "example.test"})
        self.assertEqual(fields["http"][1], {"status": 200})

    def test_capinfos_parser_on_recorded_output(self):
        info = traffic.parse_capinfos(
            _fx("re_capinfos_fixture.txt").decode())
        self.assertEqual(info["packets"], "17")
        self.assertEqual(info["encapsulation"], "Ethernet")


