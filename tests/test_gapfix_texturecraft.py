        for name, want in self.VALUES.items():
            kind = ProceduralKind.parse(name)
            assert kind is not None, name
            got = raw(kind, self.AT[0], self.AT[1], 0.0, 3)
            self.assertTrue(_close(got, want, 2e-6),
                            f"{name} = {got} want {want}")

