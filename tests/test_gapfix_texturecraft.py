    def test_bilinear_sample_matches_hand_value(self) -> None:
        from nomorals.media.textures.mipmaps import FilterMode, WrapMode, sample
        from nomorals.media.textures.tiles import TileImage
        img = TileImage(64, 64, 1)
        img.set(0, 0, [0])
        img.set(1, 0, [65535])
        img.set(0, 1, [65535])
        img.set(1, 1, [65535])
        # UV centre of the 2x2 block: bilinear of 0,65535,65535,65535.
        v = sample([img], 1.0 / 64.0, 1.0 / 64.0, 0,
                   WrapMode.CLAMP, FilterMode.BILINEAR)
        self.assertLess(abs(v[0] - 0.75 * 65535), 2000)

    def test_trilinear_blends_levels(self) -> None:
        from nomorals.media.textures.mipmaps import FilterMode, WrapMode, mipmap_chain, sample
        from nomorals.media.textures.tiles import TileImage
        img = TileImage(64, 64, 1)
        img.set(32, 32, [65535])
        chain = mipmap_chain(img)
        v0 = sample(chain, 32.5 / 64, 32.5 / 64, 0,
                    WrapMode.CLAMP, FilterMode.NEAREST)[0]
        v1 = sample(chain, 32.5 / 64, 32.5 / 64, 1,
                    WrapMode.CLAMP, FilterMode.TRILINEAR)[0]
        self.assertEqual(v0, 65535)
        self.assertLess(v1, 65535)
        self.assertGreater(v1, 0)


