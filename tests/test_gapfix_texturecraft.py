FIXTURES = Path(__file__).resolve().parent / "fixtures" / "textures"

TOL = 1e-6


def _close(a: float, b: float, tol: float = TOL) -> bool:
    return abs(a - b) <= tol


class TileTests(unittest.TestCase):
    def test_sparse_unallocated_reads_zero_and_writes_allocate(self) -> None:
        from nomorals.media.textures.tiles import TileImage
        img = TileImage(200, 130, 2)
        self.assertEqual((img.tiles_x, img.tiles_y), (4, 3))
        self.assertEqual(img.get(10, 10), [0, 0, 0, 0])
        img.set(199, 129, [7, 9])
        self.assertEqual(img.get(199, 129), [7, 9, 0, 0])
        self.assertEqual(img.allocated_count(), 1)
        self.assertEqual(sorted(img.allocated()), [(3, 2)])
        img.set(500, 500, [1, 1])
        self.assertEqual(img.get(500, 500), [0, 0, 0, 0])

    def test_clones_share_tiles_until_written(self) -> None:
        from nomorals.media.textures.tiles import TileImage
        a = TileImage(64, 64, 1)
        a.set(0, 0, [5])
        b = a.clone()
        # Same tile object is shared (identity, not equality).
        self.assertIs(a.tile_handle(0, 0), b.tile_handle(0, 0))
        a.set(1, 0, [6])
        self.assertIsNot(a.tile_handle(0, 0), b.tile_handle(0, 0))
        self.assertEqual(b.get(1, 0)[0], 0)
        self.assertEqual(a.get(1, 0)[0], 6)

    def test_tile_mut_fills_new_tiles_and_prune_frees_empty(self) -> None:
        from nomorals.media.textures.tiles import TILE_AREA, TileImage
        img = TileImage(64, 64, 2)
        img.tile_mut(0, 0, [100, 200])
        self.assertEqual(img.get(0, 0), [100, 200, 0, 0])
        self.assertEqual(img.get(63, 63), [100, 200, 0, 0])
        img.prune_empty()
        self.assertEqual(img.allocated_count(), 1)
        img.set_tile(0, 0, bytes(TILE_AREA * 2 * 2))
        img.prune_empty()
        self.assertEqual(img.allocated_count(), 0)

    def test_bytes_accounting(self) -> None:
        from nomorals.media.textures.tiles import TileImage
        img = TileImage(200, 130, 2)
        img.set(199, 129, [7, 9])
        # One allocated 64x64 tile x 2 comps x 2 bytes (upstream ground truth).
        self.assertEqual(img.bytes(), 16384)

    def test_unorm_round_trips(self) -> None:
        from nomorals.media.textures.tiles import from_u16, from_u16_signed, to_u16, to_u16_signed
        for v in (0.0, 0.25, 0.5, 1.0):
            self.assertLess(abs(from_u16(to_u16(v)) - v), 1e-4)
            self.assertLess(
                abs(from_u16_signed(to_u16_signed(v * 2.0 - 1.0))
                    - (v * 2.0 - 1.0)), 1e-4)
        self.assertEqual(to_u16(float("nan")), 0)

    def test_resample_up_and_down_keeps_values_and_sparsity(self) -> None:
        from nomorals.media.textures.tiles import TileImage
        img = TileImage(128, 128, 2)
        for y in range(64):
            for x in range(64):
                img.set(x, y, [30000, 65535])
        up = img.resampled(256, 256, [])
        self.assertEqual(up.get(40, 40)[:2], [30000, 65535])
        self.assertFalse(up.is_allocated(3, 3))
        down = img.resampled(64, 64, [])
        self.assertEqual(down.get(10, 10)[:2], [30000, 65535])
        self.assertEqual(down.get(60, 60), [0, 0, 0, 0])

    def test_remap_moves_texels_and_keeps_sparsity(self) -> None:
        import struct

        from nomorals.media.textures.tiles import TILE, TileImage
        img = TileImage(128, 128, 2)
        img.set(10, 20, [1000, 65535])
        # Mirror horizontally into a 256-wide image. The mapping gets
        # texel CENTRES (upstream remapped_tile): target texel (236, 40)
        # reads source (9.75, 20.25), bilinear of the single texel
        # (10, 20) weighted 0.25 * 0.75 -> 188 / 12288.
        def mapping(x: float, y: float) -> tuple[float, float] | None:
            if x < 256.0:
                return (128.0 - x / 2.0, y / 2.0)
            return None
        self.assertIsNone(img.remapped_tile(256, 256, 0, 0, [0, 0], mapping))
        t = img.remapped_tile(256, 256, 3, 0, [0, 0], mapping)
        self.assertIsNotNone(t)
        assert t is not None
        # Texel (44, 40) of tile (3, 0), component 0: u16 element
        # (40 * 64 + 44) * 2, byte offset * 2.
        off = ((40 * TILE + 44) * 2) * 2
        self.assertEqual(struct.unpack_from("<H", t, off)[0], 188)
        self.assertEqual(struct.unpack_from("<H", t, off + 2)[0], 12288)


