"""WhatsApp stickers: the maker must produce the TARGET platform's
format, and the bridge must send a sticker AS a sticker.

The 2026-11-26 live defect: /sticker on a replied video worked on
Telegram but on WhatsApp sent a .webm document (BIN) — the maker
built Telegram's .webm no matter the platform, and the bridge sent
by file extension, never by the sticker kind it was given.

Pinned here:
- video_to_sticker(format="webp") makes a real animated WebP
  (RIFF/WEBP magic + ANIM chunk) with the libwebp argv shape;
  the default (no format) still makes .webm via libvpx-vp9;
  an unknown format is a ConversionError, never a silent wrong
  form.
- _control_sticker on a replied video makes .webp on a WhatsApp
  chat and .webm on a Telegram chat, both sent as kind="sticker".
"""

from __future__ import annotations

import shutil
import subprocess
from pathlib import Path
from types import SimpleNamespace

import pytest

from nomorals.agents.partner.runtime_expression import (
    RuntimeExpressionMixin,
)
