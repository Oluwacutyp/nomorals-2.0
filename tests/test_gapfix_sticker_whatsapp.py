from nomorals.agents.partner.runtime_group import RuntimeGroupMixin
from nomorals.social.chat.base import ChatKind

# ── the fake ffmpeg runner (the organ test's shape) ───────────────


def _fake_runner(calls):
    def run(args, **kw):
        calls.append(list(args))
        Path(args[-1]).write_bytes(b"converted")
        return SimpleNamespace(returncode=0, stdout="", stderr="")

    return run


def test_video_to_sticker_webp_argv_shape(tmp_path):
    from nomorals.social.chat import media_convert

    src = tmp_path / "clip.mp4"
    src.write_bytes(b"mp4")
    calls: list = []
    out = media_convert.video_to_sticker(
        src, out_dir=tmp_path, runner=_fake_runner(calls),
        format="webp")
    assert out.suffix == ".webp" and out.exists()
    argv = calls[0]
    assert "libwebp" in argv and "-loop" in argv
    assert "0" in argv[argv.index("-loop") + 1:argv.index("-loop") + 2]
    assert "fps=30,scale=512:-2:flags=lanczos" in argv
    assert "-t" in argv and "3" in argv
    assert "libvpx-vp9" not in argv


