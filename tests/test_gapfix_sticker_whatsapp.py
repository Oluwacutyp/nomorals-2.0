def test_video_to_sticker_rejects_unknown_format(tmp_path):
    from nomorals.social.chat import media_convert

    src = tmp_path / "clip.mp4"
    src.write_bytes(b"mp4")
    with pytest.raises(media_convert.ConversionError):
        media_convert.video_to_sticker(
            src, out_dir=tmp_path, runner=_fake_runner([]),
            format="tgs")


def _make_test_video(tmp_path: Path) -> Path:
    """A real 1s video, generated by the local ffmpeg."""
    vid = tmp_path / "src.mp4"
    subprocess.run(
        ["ffmpeg", "-hide_banner", "-loglevel", "error", "-y",
         "-f", "lavfi", "-i", "testsrc=duration=1:size=320x240:rate=10",
         "-c:v", "libx264", "-pix_fmt", "yuv420p", str(vid)],
        check=True, timeout=60)
    assert vid.exists() and vid.stat().st_size > 1000
    return vid


@pytest.mark.skipif(not shutil.which("ffmpeg"),
                    reason="ffmpeg binary absent on this machine")
def test_video_to_sticker_webp_is_really_animated(tmp_path):
    from nomorals.social.chat import media_convert

    vid = _make_test_video(tmp_path)
    out = media_convert.video_to_sticker(
        vid, out_dir=tmp_path, format="webp")
    assert out.suffix == ".webp"
    raw = out.read_bytes()
    assert raw[:4] == b"RIFF" and raw[8:12] == b"WEBP"
    assert b"ANIM" in raw, "the WebP must carry an ANIM chunk"


@pytest.mark.skipif(not shutil.which("ffmpeg"),
                    reason="ffmpeg binary absent on this machine")
def test_video_to_sticker_webm_is_really_webm(tmp_path):
    from nomorals.social.chat import media_convert

    vid = _make_test_video(tmp_path)
    out = media_convert.video_to_sticker(vid, out_dir=tmp_path)
