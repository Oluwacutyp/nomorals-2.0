class MixTests(unittest.TestCase):
    def _doc(self):
        from nomorals.media.sound import SessionDocument
        return SessionDocument.open(FIXTURES / "simple.scraft")

    def test_two_sines_sum_sample_accurate(self) -> None:
        from nomorals.media.sound import MixEngine
        doc = self._doc()
        engine = MixEngine(doc)
        left, right, report = engine.render(0, SR)
        a, _ = _read_wav(FIXTURES / "sine440.wav")
        b, _ = _read_wav(FIXTURES / "sine880.wav")
        # Equal-power pan at centre: each channel gets 1/sqrt(2) of each
        # mono source, so the sum is (a + b) / sqrt(2).
        expect = (a + b) / math.sqrt(2.0)
        np.testing.assert_allclose(left, expect, atol=2e-4)
        np.testing.assert_allclose(right, expect, atol=2e-4)
        self.assertFalse(report["clipped"])
        self.assertAlmostEqual(report["master_peak"], float(np.max(np.abs(expect))),
                               places=3)

    def test_hard_pan_left_silences_right(self) -> None:
        from nomorals.media.sound import MixEngine, SessionEditor
        doc = self._doc()
        ed = SessionEditor(doc)
        for track in doc.tracks:
            ed.set_track_pan(track.id, -1.0)
        left, right, _ = MixEngine(doc).render(0, SR)
        self.assertGreater(_rms(left), 0.1)
        np.testing.assert_allclose(right, 0.0, atol=1e-9)

    def test_mute_silences_track(self) -> None:
        from nomorals.media.sound import MixEngine, SessionEditor
        doc = self._doc()
        ed = SessionEditor(doc)
        ed.mute_track(doc.tracks[0].id, True)
        left, _, _ = MixEngine(doc).render(0, SR)
        b, _ = _read_wav(FIXTURES / "sine880.wav")
        np.testing.assert_allclose(left, b / math.sqrt(2.0), atol=2e-4)

    def test_solo_isolates_track(self) -> None:
        from nomorals.media.sound import MixEngine, SessionEditor
        doc = self._doc()
        ed = SessionEditor(doc)
        ed.solo_track(doc.tracks[1].id, True)
        left, _, _ = MixEngine(doc).render(0, SR)
        b, _ = _read_wav(FIXTURES / "sine880.wav")
        np.testing.assert_allclose(left, b / math.sqrt(2.0), atol=2e-4)

    def test_track_gain_minus_6_halves(self) -> None:
        from nomorals.media.sound import MixEngine, SessionEditor
        doc = self._doc()
        ed = SessionEditor(doc)
        ed.set_track_gain(doc.tracks[0].id, -6.0)
        ed.mute_track(doc.tracks[1].id, True)
        left, _, _ = MixEngine(doc).render(0, SR)
        a, _ = _read_wav(FIXTURES / "sine440.wav")
        expect = a * (10.0 ** (-6.0 / 20.0)) / math.sqrt(2.0)
        np.testing.assert_allclose(left, expect, atol=2e-4)

    def test_clipping_reported_honestly_with_peak(self) -> None:
        from nomorals.media.sound import MixEngine, SessionEditor
        doc = self._doc()
        ed = SessionEditor(doc)
        ed.set_track_gain(doc.tracks[0].id, 12.0)
        ed.set_track_gain(doc.tracks[1].id, 12.0)
        _, _, report = MixEngine(doc).render(0, SR)
        self.assertTrue(report["clipped"])
        self.assertGreater(report["master_peak"], 1.0)
        self.assertIn("clip_first_sample", report)

    def test_send_reaches_aux_bus(self) -> None:
        from nomorals.media.sound import MixEngine, SessionEditor
        doc = self._doc()
        ed = SessionEditor(doc)
        aux = ed.add_bus("Reverb")
