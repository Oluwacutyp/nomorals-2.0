class EffectsTests(unittest.TestCase):
    def test_parametric_eq_boosts_its_frequency(self) -> None:
        from nomorals.media.sound.effects import ParametricEQ
        a, _ = _read_wav(FIXTURES / "sine440.wav")
        eq = ParametricEQ(SR, freq=440.0, gain_db=12.0, q=1.0)
        out = eq.process(a)
        self.assertAlmostEqual(_rms(out) / _rms(a), 10.0 ** (12.0 / 20.0),
                               delta=0.35)
        # Far from the band the signal is barely touched.
        b, _ = _read_wav(FIXTURES / "sine880.wav")
        eq2 = ParametricEQ(SR, freq=440.0, gain_db=12.0, q=4.0)
        self.assertAlmostEqual(_rms(eq2.process(b)) / _rms(b), 1.0, delta=0.15)

    def test_compressor_reduces_gain_on_loud_signal(self) -> None:
        from nomorals.media.sound.effects import Compressor
        loud = np.full(SR, 0.9)
        comp = Compressor(SR, threshold_db=-18.0, ratio=4.0,
                          attack_s=0.005, release_s=0.1)
        out = comp.process(loud)
        # The attack lets the first transient through; the settled
        # second half is where the reduction lives.
        self.assertLess(float(np.max(np.abs(out[SR // 2:]))), 0.9)
        self.assertGreater(comp.gain_reduction_db(loud), 3.0)
        quiet = np.full(SR, 0.01)
        self.assertAlmostEqual(comp.gain_reduction_db(quiet), 0.0, delta=0.5)

    def test_limiter_never_exceeds_ceiling(self) -> None:
        from nomorals.media.sound.effects import Limiter
        hot = np.concatenate([np.full(SR // 2, 0.5),
                              np.full(SR // 2, 2.0)])
        lim = Limiter(ceiling=0.95)
        out = lim.process(hot)
        self.assertLessEqual(float(np.max(np.abs(out))), 0.95 + 1e-6)

    def test_insert_chain_runs_in_track_order(self) -> None:
        from nomorals.media.sound import MixEngine, SessionDocument, SessionEditor
        from nomorals.media.sound.effects import GainPlugin
        doc = SessionDocument.open(FIXTURES / "simple.scraft")
        ed = SessionEditor(doc)
        ed.insert_plugin(doc.tracks[0].id, GainPlugin(-6.0))
        ed.mute_track(doc.tracks[1].id, True)
        left, _, _ = MixEngine(doc).render(0, SR)
        a, _ = _read_wav(FIXTURES / "sine440.wav")
        expect = a * 0.5 / math.sqrt(2.0)
        np.testing.assert_allclose(left, expect, atol=2e-3)


