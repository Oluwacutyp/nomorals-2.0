"""IDML values: observed values every InDesign-exported IDML has.

A faithful port of ``src/idml/values.rs`` from storytold/indd-utils
(commit 136f973, dual MIT/Apache-2.0 — see attribution.py). The observed
values live in the four vendored XML data files under ``values_data/``
(byte-identical to upstream's ``src/idml/*.xml``); they are generated by
upstream's ``tools/root_values.py`` / ``tools/element_values.py`` from a
corpus of real IDML exports. A values file that did not parse would give
no observed values instead of stopping every conversion.
"""

from __future__ import annotations

from pathlib import Path

_DATA = Path(__file__).resolve().parent / "values_data"


def _load(name: str) -> str:
    return (_DATA / name).read_text(encoding="utf-8")


class Node:
    """An element of a values file."""

    __slots__ = ("tag", "attrs", "text", "children")

    def __init__(self, tag="", attrs=None, text=None, children=None):
        self.tag = tag
        self.attrs = list(attrs) if attrs else []
        self.text = text
        self.children = list(children) if children else []

    def child(self, tag):
        for c in self.children:
            if c.tag == tag:
                return c
        return None

    def attr(self, name):
        for k, v in self.attrs:
            if k == name:
                return v
        return None

    def set(self, path, attrs):
        """Set the attributes of the descendant at ``path``, creating
        missing elements (``Properties`` as the first child), replacing
        values already there in place and adding the others at the end.
        Returns the descendant."""
        node = self
        for tag in path:
            found = None
            for i, c in enumerate(node.children):
                if c.tag == tag:
                    found = i
                    break
            if found is None:
                new = Node(tag=tag)
                if tag == "Properties":
                    node.children.insert(0, new)
                    found = 0
                else:
                    node.children.append(new)
                    found = len(node.children) - 1
            node = node.children[found]
        for k, v in attrs:
            for j, (a, _) in enumerate(node.attrs):
                if a == k:
                    node.attrs[j] = (k, v)
                    break
            else:
                node.attrs.append((k, v))
        return node

    def merge(self, other):
        """Add the attributes and children of ``other`` that ``self``
        lacks. Children with the same tag are merged. A typed value (an
        element with a ``type`` attribute) keeps its own text and
        children."""
        for k, v in other.attrs:
            if self.attr(k) is None:
                self.attrs.append((k, v))
        if self.attr("type") is not None:
            return
        if self.text is None:
            self.text = other.text
        for c in other.children:
            for m in self.children:
                if m.tag == c.tag:
                    m.merge(c)
                    break
            else:
                # The schema puts ``Properties`` before other children.
                if c.tag == "Properties":
                    self.children.insert(0, _clone_node(c))
                else:
                    self.children.append(_clone_node(c))

    def write(self, x):
        """Write this element and its children."""
        x.start(self.tag)
        for k, v in self.attrs:
            x.attr(k, v)
        if self.text is not None:
            x.text(self.text)
        for c in self.children:
            c.write(x)
        x.end()


def _clone_node(n):
    out = Node(tag=n.tag, attrs=list(n.attrs), text=n.text)
    out.children = [_clone_node(c) for c in n.children]
    return out


def _applies(block, major):
    """Whether a block of a values file applies to InDesign version
    ``major``: its ``MinimumVersion`` and ``MaximumVersion``, where
    present, include ``major``. A bound that is not a number excludes
    the block."""
    def bound(name):
        v = block.attr(name)
        if v is None:
            return None
        try:
            return int(v)
        except ValueError:
            return False

    lo = bound("MinimumVersion")
    hi = bound("MaximumVersion")
    ok_lo = lo is None or (lo is not False and lo <= major)
    ok_hi = hi is None or (hi is not False and major <= hi)
    return ok_lo and ok_hi


def _embedded(text):
    return _parse(text) or Node()


_ROOT_VALUES = None
_OBJECT_STYLE_VALUES = None
_PREFERENCE_VALUES = None
_ELEMENT_VALUES = None


def _root_values():
    global _ROOT_VALUES
    if _ROOT_VALUES is None:
        _ROOT_VALUES = _embedded(_load("root_values.xml"))
    return _ROOT_VALUES


def _object_style_values():
    global _OBJECT_STYLE_VALUES
    if _OBJECT_STYLE_VALUES is None:
        _OBJECT_STYLE_VALUES = _embedded(_load("object_style_values.xml"))
    return _OBJECT_STYLE_VALUES


def _preference_values():
    global _PREFERENCE_VALUES
    if _PREFERENCE_VALUES is None:
        _PREFERENCE_VALUES = _embedded(_load("preference_values.xml"))
    return _PREFERENCE_VALUES


def _element_values():
    global _ELEMENT_VALUES
    if _ELEMENT_VALUES is None:
        _ELEMENT_VALUES = _embedded(_load("element_values.xml"))
    return _ELEMENT_VALUES


def root_style(tag, major):
    """The observed values of root style element ``tag``
    (``ParagraphStyle``, ``ObjectStyle``, ...) for a document of
    InDesign version ``major``."""
    out = Node(tag=tag)
    root = _root_values()
    for block in root.children:
        if _applies(block, major):
            n = block.child(tag)
            if n is not None:
                out.merge(n)
    return out


def object_style(major):
    """The observed values of object styles other than the root
    ``[None]``, for a document of InDesign version ``major``."""
    out = Node(tag="ObjectStyle")
    root = _object_style_values()
    for block in root.children:
        if _applies(block, major):
            n = block.child("ObjectStyle")
            if n is not None:
                out.merge(n)
    return out


def preferences(major):
    """The observed preference elements (``TextDefault``, ...) for a
    document of InDesign version ``major``, in the order the IDML files
    list them."""
    root = _preference_values()
    out = []
    for block in root.children:
        if not _applies(block, major):
            continue
        for n in block.children:
            for m in out:
                if m.tag == n.tag:
                    m.merge(n)
                    break
            else:
                out.append(_clone_node(n))
    return out


def _blocks_element(block_tag, path, major):
    parent, child = path.split("/", 1) if "/" in path else (path, None)
    out = None
    for block in _element_values().children:
        if block.tag != block_tag:
            continue
        if not _applies(block, major):
            continue
        n = block.child(parent)
        if n is None:
            continue
        if child is not None:
            cn = n.child(child)
            if cn is None:
                continue
            n = cn
        n = _clone_node(n)
        if child is None:
            # Children are other paths.
            n.children = [c for c in n.children if c.tag == "Properties"]
        if out is None:
            out = n
        else:
            out.merge(n)
    return out


def element(path, major):
    """The observed values of the elements on ``path`` (a tag, or a tag
    and a child tag such as ``Spread/FlattenerPreference``) for a
    document of InDesign version ``major``, from element_values.xml.
    ``None`` if the file has no values for it."""
    return _blocks_element("Values", path, major)


def when_written(path, major):
    """The values of attributes that only some elements on ``path``
    have, for the converter to write where it writes the attribute
    (``WhenWritten`` blocks of element_values.xml)."""
    n = _blocks_element("WhenWritten", path, major)
    return list(n.attrs) if n is not None else []


def present(path, major):
    """The element on ``path`` every IDML of InDesign version ``major``
    in the corpus has (``Present="true"`` in element_values.xml), with
    its observed values; ``None`` if not every IDML has it."""
    n = element(path, major)
    if n is None:
        return None
    if n.attr("Present") != "true":
        return None
    n.attrs = [(k, v) for k, v in n.attrs if k != "Present"]
    return n


def list_values(tag, major):
    """The list of ``tag`` elements every IDML of InDesign version
    ``major`` in the corpus has, in order (``List`` blocks of
    element_values.xml); empty if there is none."""
    out = []
    for b in _element_values().children:
        if b.tag == "List" and b.attr("Tag") == tag and _applies(b, major):
            out.extend(_clone_node(c) for c in b.children)
    return out


def keyed(tag, value):
    """The observed values of a ``tag`` element whose key attribute
    (such as ``Name``) has ``value`` (``Keyed`` blocks of
    element_values.xml)."""
    for b in _element_values().children:
        if b.tag != "Keyed" or b.attr("Tag") != tag:
            continue
        key = b.attr("Key")
        if key is None:
            continue
        for n in b.children:
            if n.attr(key) == value:
                return _clone_node(n)
    return None


def element_attrs(path, major):
    """The observed attributes of the elements on ``path``, without
    ``Present``."""
    n = element(path, major)
    if n is None:
        return []
    return [(k, v) for k, v in n.attrs if k != "Present"]


def _unescape(s):
    out = []
    rest = s
    while True:
        i = rest.find("&")
        if i < 0:
            break
        out.append(rest[:i])
        rest = rest[i:]
        end = rest.find(";")
        if end < 0:
            break
        entity = rest[1:end]
        c = None
        if entity == "lt":
            c = "<"
        elif entity == "gt":
            c = ">"
        elif entity == "quot":
            c = '"'
        elif entity == "apos":
            c = "'"
        elif entity == "amp":
            c = "&"
        else:
            num = None
            if entity.startswith("#x") or entity.startswith("#X"):
                try:
                    num = int(entity[2:], 16)
                except ValueError:
                    num = None
            elif entity.startswith("#"):
                try:
                    num = int(entity[1:])
                except ValueError:
                    num = None
            if num is not None:
                try:
                    c = chr(num)
                except ValueError:
                    c = None
        if c is not None:
            out.append(c)
            rest = rest[end + 1:]
        else:
            out.append("&")
            rest = rest[1:]
    out.append(rest)
    return "".join(out)


def _parse(s):
    """Parse the small, trusted XML subset of the values file:
    elements, attributes in single or double quotes, text, comments
    and the XML declaration."""
    stack = [Node()]
    rest = s
    while rest:
        if rest.startswith("<?"):
            end = rest.find("?>")
            if end < 0:
                return None
            rest = rest[end + 2:]
        elif rest.startswith("<!--"):
            end = rest.find("-->")
            if end < 0:
                return None
            rest = rest[end + 3:]
        elif rest.startswith("</"):
            end = rest.find(">")
            if end < 0:
                return None
            rest = rest[end + 1:]
            if not stack:
                return None
            done = stack.pop()
            if not stack:
                return None
            stack[-1].children.append(done)
        elif rest.startswith("<"):
            end = rest.find(">")
            if end < 0:
                return None
            head = rest[1:end]
            empty = False
            if head.endswith("/"):
                head = head[:-1].rstrip()
                empty = True
            rest = rest[end + 1:]
            name_end = len(head)
            for i, ch in enumerate(head):
                if ch.isspace():
                    name_end = i
                    break
            node = Node(tag=head[:name_end])
            head = head[name_end:].lstrip()
            while head:
                eq = head.find("=")
                if eq < 0:
                    return None
                key = head[:eq].strip()
                value = head[eq + 1:].lstrip()
                if not value:
                    return None
                quote = value[0]
                close = value[1:].find(quote)
                if close < 0:
                    return None
                close += 1
                node.attrs.append((key, _unescape(value[1:close])))
                head = value[close + 1:].lstrip()
            if empty:
                stack[-1].children.append(node)
            else:
                stack.append(node)
        else:
            end = rest.find("<")
            if end < 0:
                end = len(rest)
            text = rest[:end]
            if text.strip():
                stack[-1].text = _unescape(text)
            rest = rest[end:]
    if len(stack) != 1:
        return None
    top = stack.pop()
    if not top.children:
        return None
    return top.children.pop()
