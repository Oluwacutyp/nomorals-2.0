"""Exness connector — forex/CFD trading on the owner's Exness account.

Endpoint + signing map MINED 2026-10-09 (not guessed):

* Official docs: https://www.exness-api.com/documentation/create-api-key —
  API keys are created in the Personal Area's Key Management (never through
  the API); the client stores ``EXN_API_KEY`` (public key id),
  ``EXN_PRIVATE_KEY`` (the secret, shown once), ``EXN_ACCOUNT_ID`` (the
  trading account the key may touch), and ``EXN_API_BASE_URL`` (the host
  from the DNS widget; ``https://api.exness.com`` is the main host).
* Path + signing semantics verified against the working third-party SDK
  ``realm-dev/exnesssdk`` (``src/auth/signer.ts``, ``src/api/*.ts``):
  every request is signed with Ed25519 over the UTF-8 bytes of a JSON
  payload ``{"api_key", "idempotency_key", "timestamp", "sign_version": 1,
  "method", "path" (path+query exactly as transmitted), "body_hash"}``;
  the signature and the base64url payload ride in the ``EXN-SIGN`` /
  ``EXN-DATA`` headers alongside ``EXN-API-KEY``, ``EXN-TIMESTAMP``,
  ``EXN-SIGN-VERSION``, ``EXN-IDEMPOTENCY-KEY``. The server tolerates
  ``0 <= server_now_ms - timestamp_ms <= 3000`` (asymmetric — a client
  clock even slightly ahead is rejected), so this client biases its clock
  1s into the past and learns the offset from HTTP ``Date`` headers.
* Trading calls run against the per-account access point discovered via
  ``GET /v1/trading/access-point?account_id=...``; configuration and
  market-data calls run against the main host.

The Ed25519 below is a native RFC 8032 implementation (extended twisted-
Edwards coordinates — one modular inverse per signature, ~7ms). It is
verified in the test-suite against a signature generated by an
independent implementation (``cryptography``), not against itself.

Money safety (mirrors the Duffel architecture):

* ``open_position`` / ``close_position`` / ``close_all_positions`` /
  ``place_pending_order`` / ``modify_order`` / ``cancel_order(s)`` move
  real money and refuse to run without explicit owner confirmation
  (``confirmed=True`` after the owner approved the exact payload, or a
  human checkpoint when ``db`` is given). No silent success.
* Demo-first: connect with a demo trading account id while testing.

Auth: ``AuthMethod.API_KEY``. Env vars: ``EXNESS_API_KEY``,
``EXNESS_PRIVATE_KEY`` (the 32-byte seed as base64url, base64, or hex),
``EXNESS_ACCOUNT_ID``, ``EXNESS_API_BASE_URL`` (optional).
"""

