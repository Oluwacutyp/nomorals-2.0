    def place_pending_order(
        self,
        order_type: str,
        instrument: str = "",
        side: str = "",
        volume: float = 0,
        *,
        price: float | None = None,
        stop_loss: float | None = None,
        take_profit: float | None = None,
        position_id: str = "",
        comment: str = "",
        idempotency_key: str | None = None,
        confirmed: bool = False,
        db: Any = None,
        context: Any = None,
    ) -> dict[str, Any]:
        """Place a limit / stop / sltp pending order. Confirmation-gated."""
        account_id, *_ = self._auth()
        order_type = (order_type or "").strip().lower()
        if order_type not in ("limit", "stop", "sltp"):
            raise ExnessError(
                f"order_type must be limit|stop|sltp, got {order_type!r}"
            )
        if order_type == "sltp":
            body: dict[str, Any] = {
                "type": "sltp",
                "position_id": (position_id or "").strip(),
            }
            if not body["position_id"]:
                raise ExnessError("sltp orders need position_id")
        else:
            instrument = (instrument or "").strip().upper()
            side = (side or "").strip().lower()
            if not instrument or side not in ("buy", "sell") or not volume:
                raise ExnessError(
                    "limit/stop orders need instrument, side (buy|sell), "
                    "volume, and price"
                )
            if price is None:
                raise ExnessError("limit/stop orders need price")
            priced = self._format_prices(
                instrument, price=price, stop_loss_price=stop_loss,
                take_profit_price=take_profit,
            )
            body = {
                "type": order_type,
                "instrument": instrument,
                "side": side,
                "volume": str(volume),
                **priced,
            }
        if comment:
            body["comment"] = comment[:128]
        self._gate(
            confirmed=confirmed, db=db, context=context,
            stage="place_pending_order",
            title=f"Exness: {order_type} order {body.get('instrument', '')}",
            instructions="\n".join([
                "Devon wants to place a pending order on Exness.",
                f"account={account_id} order={body}",
                "Approve ONLY if the order above is exactly what you want.",
            ]),
            resume_state={"op": "place_pending_order", "body": body,
                          "idempotency_key": idempotency_key or uuid.uuid4().hex},
        )
        return self._api(
            "POST",
            f"/v1/trading/accounts/{account_id}/orders",
            host_kind="trading",
            json_body=body,
            idempotency_key=idempotency_key,
        )

