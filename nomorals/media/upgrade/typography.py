"""Tier 1 — Text-as-compositing.

Text is NEVER generated by the image model: the model renders the
scene without text, and real typography is composited on top with
PIL. :class:`TextComposite` is the compositing spec (string, font,
size, colour, position, stroke, box, rotation). :func:`composite_text`
draws it onto a copy of the image and returns the composited image —
the source image is never mutated. If no font file is supplied, PIL's
built-in bitmap font is used (deterministic, always available).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Any

POSITIONS = ("top", "center", "bottom", "top-left", "top-right",
             "bottom-left", "bottom-right")


@dataclass
class TextComposite:
    text: str
    position: str = "bottom"
    size: int = 48
    color: str = "white"
    stroke: int = 2
    stroke_color: str = "black"
    box: bool = False
    box_color: str = "#00000099"
    rotation: float = 0.0
    font_path: str | None = None
    x: float | None = None  # normalised 0..1 override
    y: float | None = None

    def __post_init__(self) -> None:
        if not self.text:
            raise ValueError("TextComposite needs non-empty text")
        if self.position not in POSITIONS:
            raise ValueError(f"unknown position {self.position!r}")
        if self.size <= 0:
            raise ValueError("size must be > 0")

    def to_dict(self) -> dict[str, Any]:
        return {"text": self.text, "position": self.position, "size": self.size,
                "color": self.color, "stroke": self.stroke,
                "stroke_color": self.stroke_color, "box": self.box,
                "box_color": self.box_color, "rotation": self.rotation,
                "font_path": self.font_path, "x": self.x, "y": self.y}


def composite_text(image: Any, layers: list[TextComposite] | TextComposite) -> Any:
    """Composite real typography onto a copy of ``image``.

    Invariant: the input image is never mutated; the returned image
    carries exactly the supplied layers, rendered by PIL, not by any
    generative model.
    """
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError as exc:
        raise RuntimeError("composite_text needs Pillow") from exc
    if isinstance(layers, TextComposite):
        layers = [layers]
    out = image.copy()
    draw = ImageDraw.Draw(out, "RGBA")
    w, h = out.size
    for layer in layers:
        try:
            font = (ImageFont.truetype(layer.font_path, layer.size)
                    if layer.font_path else ImageFont.load_default(size=layer.size))
        except Exception:
            font = ImageFont.load_default()
        bbox = draw.textbbox((0, 0), layer.text, font=font, stroke_width=layer.stroke)
        tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
        if layer.x is not None and layer.y is not None:
            x, y = layer.x * w, layer.y * h
        else:
            x = {"top-left": 24, "bottom-left": 24, "top-right": w - tw - 24,
                 "bottom-right": w - tw - 24}.get(layer.position, (w - tw) / 2)
            y = {"top": 24, "top-left": 24, "top-right": 24}.get(
                layer.position, h - th - 24 if "bottom" in layer.position else (h - th) / 2)
        if layer.box:
            draw.rectangle([x - 8, y - 8, x + tw + 8, y + th + 8], fill=layer.box_color)
        draw.text((x, y), layer.text, font=font, fill=layer.color,
                  stroke_width=layer.stroke, stroke_fill=layer.stroke_color)
    return out
